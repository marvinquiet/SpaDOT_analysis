# usage: Rscript run_precast.R <bridge/timepoint> <output-dir> <K>
args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==3)
input <- args[[1]]; output <- args[[2]]; K <- as.integer(args[[3]])
if(dir.exists(output)) stop("Output collision")

suppressPackageStartupMessages(library(Matrix))
suppressPackageStartupMessages(library(rlang))
suppressPackageStartupMessages(library(lifecycle))
suppressPackageStartupMessages(library(SeuratObject))
suppressPackageStartupMessages(library(Seurat))
suppressPackageStartupMessages(library(PRECAST))
options(Seurat.object.assay.version="v3")
set.seed(2024)
dir.create(output, recursive=TRUE)
writeLines(capture.output(sessionInfo()),file.path(output,"sessionInfo.txt"))
genes <- readLines(file.path(input,"genes.txt"))
spots <- readLines(file.path(input,"spots.txt"))
coords <- read.csv(file.path(input,"coordinates.csv"),stringsAsFactors=FALSE)
stopifnot(identical(coords$spot,spots))
counts <- as(Matrix::readMM(file.path(input,"counts_genes_by_spots.mtx")),"CsparseMatrix")
stopifnot(identical(dim(counts),c(length(genes),length(spots))))
rownames(counts)<-genes; colnames(counts)<-spots
seu<-Seurat::CreateSeuratObject(counts=counts,meta.data=data.frame(row=coords$pixel_x,col=coords$pixel_y,row.names=spots))
preobj<-PRECAST::CreatePRECASTObject(seuList=list(seu),selectGenesMethod="HVGs",gene.number=2000)
preobj<-PRECAST::AddAdjList(preobj,type="fixed_number",number=6)
preobj<-PRECAST::AddParSetting(preobj,Sigma_equal=FALSE,coreNum=1,maxIter=30,verbose=TRUE)
writeLines(capture.output(preobj@parameterList),file.path(output,"native_parameters.txt"))
writeLines(colnames(preobj@seulist[[1]]),file.path(output,"preprocessed_spots.txt"))
writeLines(rownames(preobj@seulist[[1]]),file.path(output,"selected_genes.txt"))
fitted<-PRECAST::PRECAST(preobj,K=K)
fitted<-PRECAST::SelectModel(fitted)
fitted_spots<-colnames(fitted@seulist[[1]])
predicted<-as.vector(fitted@resList$cluster[[1]])
latent<-as.matrix(fitted@resList$hZ[[1]])
if(nrow(latent)!=length(fitted_spots) && ncol(latent)==length(fitted_spots)) latent<-t(latent)
stopifnot(!anyDuplicated(fitted_spots),all(fitted_spots %in% spots),length(predicted)==length(fitted_spots),all(is.finite(latent)),nrow(latent)==length(fitted_spots))
write.csv(data.frame(spot=fitted_spots,predicted=predicted),file.path(output,"predicted.csv"),row.names=FALSE)
write.csv(data.frame(spot=fitted_spots,latent),file.path(output,"latent.csv"),row.names=FALSE)
saveRDS(fitted,file.path(output,"native_precast.rds"))
writeLines("COMPLETE",file.path(output,"status.txt"))
